CREATE TABLE public.envios (
  id_excel bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_paquete text,
  tracking_code text NOT NULL UNIQUE,
  cliente_nombre text,
  cliente_telefono text,
  total_a_pagar text,
  perfil text,
  ruta_id text,
  ruta_nombre text,
  ruta_estado text,
  ruta_fecha_inicio text,
  ruta_fecha_fin text,
  ruta_fecha_actualizacion text,
  direccion_entrega text,
  locality text,
  estado_envio text NOT NULL DEFAULT 'en sucursal',
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  ultima_actualizacion timestamptz NOT NULL DEFAULT now(),
  notificacion_pendiente boolean NOT NULL DEFAULT false
);

CREATE TABLE public."Xcargo" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_code text NOT NULL UNIQUE,
  cliente_nombre text,
  cliente_telefono text,
  ubicacion text,
  almacen text,
  estado_envio text NOT NULL DEFAULT 'en sucursal',
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  ultima_actualizacion timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.envios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Xcargo" ENABLE ROW LEVEL SECURITY;

CREATE POLICY xcargo_admin_guard
  ON public."Xcargo"
  AS RESTRICTIVE
  FOR ALL
  TO anon, authenticated
  USING ((auth.jwt() -> 'app_metadata' ->> 'role') IN ('admin', 'editor'))
  WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'role') IN ('admin', 'editor'));

CREATE POLICY xcargo_admin_access
  ON public."Xcargo"
  FOR ALL
  TO authenticated
  USING ((auth.jwt() -> 'app_metadata' ->> 'role') IN ('admin', 'editor'))
  WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'role') IN ('admin', 'editor'));

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public."Xcargo" TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;