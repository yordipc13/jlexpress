
CREATE TABLE IF NOT EXISTS public.paquetes_ruta (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_paquete text,
  tracking_code text NOT NULL UNIQUE,
  cliente_nombre text,
  cliente_telefono text,
  total_a_pagar text,
  perfil text,
  ruta_id text,
  ruta_nombre text,
  ruta_estado text,
  ruta_fecha_inicio text,
  ruta_fecha_fin text,
  ruta_fecha_actualizacion text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS paquetes_ruta_id_paquete_unique
  ON public.paquetes_ruta (id_paquete)
  WHERE id_paquete IS NOT NULL AND btrim(id_paquete) <> '';

ALTER TABLE public.paquetes_ruta ENABLE ROW LEVEL SECURITY;

