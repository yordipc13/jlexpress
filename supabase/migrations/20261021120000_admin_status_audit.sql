CREATE OR REPLACE FUNCTION public.record_admin_status_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  old_row jsonb := pg_catalog.to_jsonb(OLD);
  new_row jsonb := pg_catalog.to_jsonb(NEW);
  status_column text := TG_ARGV[0];
BEGIN
  IF old_row ->> status_column IS NOT DISTINCT FROM new_row ->> status_column THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.admin_status_audit (
    source_table,
    record_id,
    tracking_code,
    cliente_nombre,
    previous_status,
    new_status,
    actor_user_id,
    actor_email
  )
  VALUES (
    TG_TABLE_NAME,
    new_row ->> TG_ARGV[1],
    new_row ->> 'tracking_code',
    new_row ->> 'cliente_nombre',
    old_row ->> status_column,
    new_row ->> status_column,
    auth.uid(),
    NULLIF(auth.jwt() ->> 'email', '')
  );

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.record_admin_status_change() FROM PUBLIC, anon, authenticated, service_role;

DROP TRIGGER IF EXISTS envios_status_audit ON public.envios;
CREATE TRIGGER envios_status_audit
  AFTER UPDATE OF estado_envio ON public.envios
  FOR EACH ROW
