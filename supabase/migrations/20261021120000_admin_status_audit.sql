DO $$
BEGIN
  IF pg_catalog.to_regclass('public.envios') IS NULL
    OR pg_catalog.to_regclass('public.paquetes_ruta') IS NULL
    OR pg_catalog.to_regclass('public."Xcargo"') IS NULL THEN
    RAISE EXCEPTION 'La auditoría requiere public.envios, public.paquetes_ruta y public."Xcargo".';
  END IF;

  IF (
    SELECT pg_catalog.count(*)
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND (
        (table_name = 'envios' AND column_name IN ('id_excel', 'tracking_code', 'cliente_nombre', 'estado_envio'))
        OR (table_name = 'paquetes_ruta' AND column_name IN ('id', 'tracking_code', 'cliente_nombre', 'ruta_estado'))
        OR (table_name = 'Xcargo' AND column_name IN ('id', 'tracking_code', 'cliente_nombre', 'estado_envio'))
      )
  ) <> 12 THEN
    RAISE EXCEPTION 'Las tablas de envíos no tienen las columnas requeridas para registrar cambios de estado.';
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.admin_status_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_table text NOT NULL,
  record_id text NOT NULL,
  tracking_code text,
  cliente_nombre text,
  previous_status text,
  new_status text,
  actor_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_email text,
  changed_at timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp()
);

CREATE INDEX IF NOT EXISTS admin_status_audit_changed_at_idx
  ON public.admin_status_audit (changed_at DESC);
CREATE INDEX IF NOT EXISTS admin_status_audit_tracking_code_idx
  ON public.admin_status_audit (tracking_code);

ALTER TABLE public.admin_status_audit ENABLE ROW LEVEL SECURITY;

