CREATE OR REPLACE FUNCTION public.record_admin_activity_truncate()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  removed_count bigint;
BEGIN
  IF public.current_app_role() NOT IN ('admin', 'editor') THEN
    RAISE EXCEPTION 'Se requiere una cuenta administradora o editora para borrar envíos.';
  END IF;

  SELECT pg_catalog.count(*) INTO removed_count FROM public.envios;
  INSERT INTO public.admin_activity_logs (action, message, actor_user_id, actor_email)
  VALUES (
    'pedido_borrado',
    pg_catalog.format('Se borraron todos los envíos (%s registros).', removed_count),
    (SELECT auth.uid()),
    NULLIF(auth.jwt() ->> 'email', '')
  );
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS envios_admin_activity_truncate ON public.envios;
CREATE TRIGGER envios_admin_activity_truncate
  BEFORE TRUNCATE ON public.envios
  FOR EACH STATEMENT EXECUTE FUNCTION public.record_admin_activity_truncate();

CREATE OR REPLACE FUNCTION public.record_delivery_assignment_activity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  assignment_row public.delivery_assignments%ROWTYPE;
  courier_name text;
  action_name text;
  message_text text;
  source_name text;
BEGIN
  assignment_row := CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  source_name := CASE assignment_row.source_table
    WHEN 'envios' THEN 'Envío'
    WHEN 'paquetes_ruta' THEN 'Paquete de ruta'
    ELSE 'Xcargo'
  END;

  IF TG_OP = 'DELETE' THEN
    action_name := 'asignacion_retirada';
    message_text := pg_catalog.format(
      'Se retiró la asignación del %s %s.',
      source_name,
      assignment_row.tracking_code
    );
  ELSE
    SELECT COALESCE(
      account.raw_user_meta_data ->> 'full_name',
      account.raw_user_meta_data ->> 'name',
      account.email,
      'repartidor'
    )
    INTO courier_name
    FROM auth.users AS account
    WHERE account.id = assignment_row.courier_user_id;
    action_name := 'repartidor_asignado';
    message_text := pg_catalog.format(
      'Se asignó el %s %s a %s.',
      source_name,
      assignment_row.tracking_code,
      COALESCE(courier_name, 'repartidor')
    );
  END IF;

  INSERT INTO public.admin_activity_logs (action, message, actor_user_id, actor_email)
  VALUES (
    action_name,
    message_text,
    (SELECT auth.uid()),
    NULLIF(auth.jwt() ->> 'email', '')
  );
  DELETE FROM public.admin_activity_logs
  WHERE created_at < pg_catalog.clock_timestamp() - interval '7 days';
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS delivery_assignments_admin_activity_log ON public.delivery_assignments;
CREATE TRIGGER delivery_assignments_admin_activity_log
  AFTER INSERT OR UPDATE OR DELETE ON public.delivery_assignments
  FOR EACH ROW EXECUTE FUNCTION public.record_delivery_assignment_activity();

