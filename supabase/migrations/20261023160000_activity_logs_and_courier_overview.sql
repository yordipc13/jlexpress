CREATE OR REPLACE FUNCTION public.log_admin_activity(
  p_action text,
  p_message text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF public.current_app_role() NOT IN ('admin', 'editor') THEN
    RAISE EXCEPTION 'Se requiere una cuenta administradora o editora para registrar actividad.';
  END IF;
  IF p_action IS DISTINCT FROM 'archivo_importado'
    OR p_message IS NULL
    OR pg_catalog.length(pg_catalog.btrim(p_message)) = 0
    OR pg_catalog.length(p_message) > 600 THEN
    RAISE EXCEPTION 'El registro de actividad no es válido.';
  END IF;

  INSERT INTO public.admin_activity_logs (action, message, actor_user_id, actor_email)
  VALUES (
    p_action,
    p_message,
    (SELECT auth.uid()),
    NULLIF(auth.jwt() ->> 'email', '')
  );

  DELETE FROM public.admin_activity_logs
  WHERE created_at < pg_catalog.clock_timestamp() - interval '7 days';
END;
$$;

REVOKE ALL ON FUNCTION public.log_admin_activity(text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.log_admin_activity(text, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.get_admin_activity_logs(p_action text DEFAULT NULL)
RETURNS TABLE (
  id bigint,
  action text,
  message text,
  actor_email text,
  created_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF public.current_app_role() NOT IN ('admin', 'editor') THEN
    RAISE EXCEPTION 'Se requiere una cuenta administradora o editora para consultar los logs.';
  END IF;
  IF p_action IS NOT NULL AND p_action NOT IN (
    'pedido_agregado',
    'pedido_editado',
    'pedido_borrado',
    'estado_cambiado',
    'pedido_finalizado',
    'repartidor_finalizo_pedido',
    'archivo_importado',
    'repartidor_asignado',
    'asignacion_retirada',
    'usuario_agregado',
    'rol_cambiado',
    'usuario_eliminado'
  ) THEN
    RAISE EXCEPTION 'El filtro de actividad no es válido.';
  END IF;

  DELETE FROM public.admin_activity_logs
  WHERE created_at < pg_catalog.clock_timestamp() - interval '7 days';

  RETURN QUERY
  SELECT log.id, log.action, log.message, log.actor_email, log.created_at
  FROM public.admin_activity_logs AS log
  WHERE log.created_at >= pg_catalog.clock_timestamp() - interval '7 days'
    AND (p_action IS NULL OR log.action = p_action)
  ORDER BY log.created_at DESC
  LIMIT 1000;
END;
$$;

REVOKE ALL ON FUNCTION public.get_admin_activity_logs(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_admin_activity_logs(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.record_admin_activity_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  old_row jsonb;
  new_row jsonb;
  source_name text;
  tracking_code text;
  customer_name text;
  status_column text;
  old_status text;
  new_status text;
  action_name text;
  message_text text;
  actor_role text := public.current_app_role();
BEGIN
  IF TG_OP <> 'INSERT' THEN old_row := pg_catalog.to_jsonb(OLD); END IF;
  IF TG_OP <> 'DELETE' THEN new_row := pg_catalog.to_jsonb(NEW); END IF;
  source_name := CASE TG_TABLE_NAME
    WHEN 'envios' THEN 'Envío'
    WHEN 'paquetes_ruta' THEN 'Paquete de ruta'
    ELSE 'Xcargo'
  END;
  tracking_code := COALESCE(new_row ->> 'tracking_code', old_row ->> 'tracking_code', 'sin guía');
  customer_name := COALESCE(new_row ->> 'cliente_nombre', old_row ->> 'cliente_nombre', 'sin cliente');
  status_column := CASE TG_TABLE_NAME WHEN 'paquetes_ruta' THEN 'ruta_estado' ELSE 'estado_envio' END;
  old_status := old_row ->> status_column;
  new_status := new_row ->> status_column;

  IF TG_OP = 'UPDATE'
    AND old_status IS NOT DISTINCT FROM new_status
    AND (old_row - 'ultima_actualizacion' - 'updated_at')
      IS NOT DISTINCT FROM (new_row - 'ultima_actualizacion' - 'updated_at') THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' THEN
    action_name := 'pedido_agregado';
    message_text := pg_catalog.format('%s %s agregado para %s.', source_name, tracking_code, customer_name);
  ELSIF TG_OP = 'DELETE' THEN
    action_name := 'pedido_borrado';
    message_text := pg_catalog.format('%s %s borrado (cliente: %s).', source_name, tracking_code, customer_name);
  ELSIF old_status IS DISTINCT FROM new_status THEN
    IF actor_role = 'repartidor'
      AND pg_catalog.lower(pg_catalog.btrim(COALESCE(new_status, ''))) IN ('recibido', 'entregado') THEN
      action_name := 'repartidor_finalizo_pedido';
      message_text := pg_catalog.format(
        'El repartidor marcó como recibido el pedido %s (cliente: %s).',
        tracking_code,
        customer_name
      );
    ELSIF pg_catalog.lower(pg_catalog.btrim(COALESCE(new_status, ''))) IN ('recibido', 'entregado', 'inactivo') THEN
      action_name := 'pedido_finalizado';
      message_text := pg_catalog.format(
        '%s %s finalizado: %s → %s.',
        source_name,
        tracking_code,
        COALESCE(old_status, 'sin estado'),
        COALESCE(new_status, 'sin estado')
      );
    ELSE
      action_name := 'estado_cambiado';
      message_text := pg_catalog.format(
        'Estado de %s %s cambiado: %s → %s.',
        source_name,
        tracking_code,
        COALESCE(old_status, 'sin estado'),
        COALESCE(new_status, 'sin estado')
      );
    END IF;
  ELSE
    action_name := 'pedido_editado';
    message_text := pg_catalog.format('%s %s editado (cliente: %s).', source_name, tracking_code, customer_name);
  END IF;

  INSERT INTO public.admin_activity_logs (action, message, actor_user_id, actor_email)
  VALUES (
    action_name,
    message_text,
    (SELECT auth.uid()),
    NULLIF(auth.jwt() ->> 'email', '')
  );
  IF TG_OP = 'UPDATE'
    AND old_status IS DISTINCT FROM new_status
    AND (old_row - status_column - 'ultima_actualizacion' - 'updated_at')
      IS DISTINCT FROM (new_row - status_column - 'ultima_actualizacion' - 'updated_at') THEN
    INSERT INTO public.admin_activity_logs (action, message, actor_user_id, actor_email)
    VALUES (
      'pedido_editado',
      pg_catalog.format('%s %s editado (cliente: %s).', source_name, tracking_code, customer_name),
      (SELECT auth.uid()),
      NULLIF(auth.jwt() ->> 'email', '')
    );
  END IF;
  DELETE FROM public.admin_activity_logs
  WHERE created_at < pg_catalog.clock_timestamp() - interval '7 days';
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

