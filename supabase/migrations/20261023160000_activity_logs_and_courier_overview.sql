CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;

CREATE TABLE IF NOT EXISTS public.admin_activity_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action text NOT NULL CHECK (action IN (
    'pedido_agregado',
    'pedido_editado',
    'pedido_borrado',
    'estado_cambiado',
    'pedido_finalizado',
    'repartidor_finalizo_pedido',
    'archivo_importado',
    'repartidor_asignado',
    'asignacion_retirada',
    'usuario_agregado',
    'rol_cambiado',
    'usuario_eliminado'
  )),
  message text NOT NULL CHECK (length(message) <= 600),
  actor_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_email text,
  created_at timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp()
);

CREATE INDEX IF NOT EXISTS admin_activity_logs_created_at_idx
  ON public.admin_activity_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS admin_activity_logs_action_created_at_idx
  ON public.admin_activity_logs (action, created_at DESC);

ALTER TABLE public.admin_activity_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_activity_logs FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.admin_activity_logs TO authenticated;
GRANT INSERT ON TABLE public.admin_activity_logs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.admin_activity_logs_id_seq TO service_role;

