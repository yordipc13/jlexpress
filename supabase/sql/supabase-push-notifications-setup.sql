CREATE TABLE IF NOT EXISTS public.notificaciones_push (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_code text NOT NULL,
  endpoint text NOT NULL,
  p256dh text NOT NULL,
  auth text NOT NULL,
  consented_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tracking_code, endpoint)
);

CREATE INDEX IF NOT EXISTS notificaciones_push_tracking_code_idx
  ON public.notificaciones_push (tracking_code);

ALTER TABLE public.notificaciones_push ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.notificaciones_push FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.notificaciones_push TO service_role;

DO $$
DECLARE
  sequence_name text;
BEGIN
  sequence_name := pg_catalog.pg_get_serial_sequence('public.notificaciones_push', 'id');
  IF sequence_name IS NOT NULL THEN
    EXECUTE pg_catalog.format('GRANT USAGE, SELECT ON SEQUENCE %s TO service_role', sequence_name);
  END IF;
END;
$$;
