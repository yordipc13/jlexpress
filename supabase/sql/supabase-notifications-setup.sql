CREATE TABLE IF NOT EXISTS public.notificaciones_envio (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_code text NOT NULL,
  email text NOT NULL,
  cliente_nombre text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pending',
  consented_at timestamptz,
  confirmed_at timestamptz,
  unsubscribed_at timestamptz,
  confirmation_token_hash text,
  confirmation_expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tracking_code, email)
);

ALTER TABLE public.notificaciones_envio
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS consented_at timestamptz,
  ADD COLUMN IF NOT EXISTS confirmed_at timestamptz,
  ADD COLUMN IF NOT EXISTS unsubscribed_at timestamptz,
  ADD COLUMN IF NOT EXISTS confirmation_token_hash text,
  ADD COLUMN IF NOT EXISTS confirmation_expires_at timestamptz;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_constraint
    WHERE conname = 'notificaciones_envio_status_check'
      AND conrelid = 'public.notificaciones_envio'::regclass
  ) THEN
    ALTER TABLE public.notificaciones_envio
      ADD CONSTRAINT notificaciones_envio_status_check
      CHECK (status IN ('pending', 'active', 'unsubscribed'));
  END IF;
END;
$$;

ALTER TABLE public.notificaciones_envio ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.notificaciones_envio FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.notificaciones_envio TO service_role;

CREATE INDEX IF NOT EXISTS notificaciones_envio_active_tracking_idx
  ON public.notificaciones_envio (tracking_code)
  WHERE status = 'active';

CREATE UNIQUE INDEX IF NOT EXISTS notificaciones_envio_confirmation_token_idx
  ON public.notificaciones_envio (confirmation_token_hash)
  WHERE confirmation_token_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.notificaciones_solicitudes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope text NOT NULL CHECK (scope IN ('email', 'tracking_code')),
  subject_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS notificaciones_solicitudes_lookup_idx
  ON public.notificaciones_solicitudes (scope, subject_hash, created_at DESC);

ALTER TABLE public.notificaciones_solicitudes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.notificaciones_solicitudes FROM PUBLIC, anon, authenticated, service_role;

DROP FUNCTION IF EXISTS public.suscribirse_notificaciones(text, text);

CREATE OR REPLACE FUNCTION public.solicitar_suscripcion_notificaciones(
  p_tracking_code text,
  p_email text,
  p_consent boolean,
  p_confirmation_token_hash text
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  normalized_tracking_code text := pg_catalog.upper(pg_catalog.btrim(p_tracking_code));
  normalized_email text := pg_catalog.lower(pg_catalog.btrim(p_email));
  shipment_customer_name text;
  email_hash text;
  tracking_hash text;
  recent_requests integer;
  request_status text;
BEGIN
  IF p_consent IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'Debes aceptar el consentimiento para recibir avisos.';
  END IF;

  IF normalized_tracking_code IS NULL OR normalized_tracking_code = '' THEN
    RAISE EXCEPTION 'El código de seguimiento es obligatorio.';
  END IF;

  IF normalized_email IS NULL
    OR pg_catalog.length(normalized_email) > 254
    OR pg_catalog.strpos(normalized_email, '@') < 2
    OR normalized_email ~ '[[:space:]]'
  THEN
    RAISE EXCEPTION 'Ingresa un correo electrónico válido.';
  END IF;

  IF p_confirmation_token_hash IS NULL OR p_confirmation_token_hash !~ '^[a-f0-9]{64}$' THEN
    RAISE EXCEPTION 'No se pudo procesar la solicitud.';
  END IF;

  SELECT COALESCE(envio.cliente_nombre, '')
  INTO shipment_customer_name
  FROM public.envios AS envio
  WHERE pg_catalog.upper(pg_catalog.btrim(envio.tracking_code)) = normalized_tracking_code
  LIMIT 1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No encontramos un envío con ese código.';
  END IF;

  email_hash := pg_catalog.md5(normalized_email);
  tracking_hash := pg_catalog.md5(normalized_tracking_code);

  PERFORM pg_catalog.pg_advisory_xact_lock(
    LEAST(
      pg_catalog.hashtext('email:' || email_hash),
      pg_catalog.hashtext('tracking:' || tracking_hash)
    )::bigint
  );
  PERFORM pg_catalog.pg_advisory_xact_lock(
    GREATEST(
      pg_catalog.hashtext('email:' || email_hash),
      pg_catalog.hashtext('tracking:' || tracking_hash)
    )::bigint
  );

  DELETE FROM public.notificaciones_solicitudes
  WHERE created_at < pg_catalog.now() - interval '24 hours';

  SELECT pg_catalog.count(*)::integer
  INTO recent_requests
  FROM public.notificaciones_solicitudes
  WHERE scope = 'email'
    AND subject_hash = email_hash
    AND created_at > pg_catalog.now() - interval '15 minutes';

  IF recent_requests >= 3 THEN
    RAISE EXCEPTION 'Demasiadas solicitudes para este correo. Inténtalo más tarde.';
  END IF;

  SELECT pg_catalog.count(*)::integer
  INTO recent_requests
  FROM public.notificaciones_solicitudes
  WHERE scope = 'tracking_code'
    AND subject_hash = tracking_hash
    AND created_at > pg_catalog.now() - interval '1 hour';

  IF recent_requests >= 10 THEN
    RAISE EXCEPTION 'Demasiadas solicitudes para este envío. Inténtalo más tarde.';
  END IF;

  INSERT INTO public.notificaciones_solicitudes (scope, subject_hash)
  VALUES ('email', email_hash), ('tracking_code', tracking_hash);

  INSERT INTO public.notificaciones_envio (
    tracking_code,
    email,
    cliente_nombre,
    status,
    consented_at,
    confirmed_at,
    unsubscribed_at,
    confirmation_token_hash,
    confirmation_expires_at,
    created_at
  )
  VALUES (
    normalized_tracking_code,
    normalized_email,
    shipment_customer_name,
    'pending',
    pg_catalog.now(),
    NULL,
    NULL,
    p_confirmation_token_hash,
    pg_catalog.now() + interval '24 hours',
    pg_catalog.now()
  )
  ON CONFLICT (tracking_code, email) DO UPDATE
    SET cliente_nombre = EXCLUDED.cliente_nombre,
        status = 'pending',
        consented_at = EXCLUDED.consented_at,
        confirmed_at = NULL,
        unsubscribed_at = NULL,
        confirmation_token_hash = EXCLUDED.confirmation_token_hash,
        confirmation_expires_at = EXCLUDED.confirmation_expires_at,
        created_at = EXCLUDED.created_at
    WHERE public.notificaciones_envio.status <> 'active'
  RETURNING status INTO request_status;

  IF NOT FOUND THEN
    RETURN 'already_active';
  END IF;

  RETURN request_status;
END;
$$;

CREATE OR REPLACE FUNCTION public.confirmar_suscripcion_notificaciones(p_token_hash text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_token_hash IS NULL OR p_token_hash !~ '^[a-f0-9]{64}$' THEN
    RETURN false;
  END IF;

  UPDATE public.notificaciones_envio
  SET status = 'active',
      confirmed_at = pg_catalog.now(),
      confirmation_token_hash = NULL,
      confirmation_expires_at = NULL
  WHERE confirmation_token_hash = p_token_hash
    AND status = 'pending'
    AND confirmation_expires_at > pg_catalog.now();

  RETURN FOUND;
END;
$$;

CREATE OR REPLACE FUNCTION public.cancelar_suscripcion_notificaciones(p_subscription_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_subscription_id IS NULL OR p_subscription_id <= 0 THEN
    RETURN false;
  END IF;

  UPDATE public.notificaciones_envio
  SET status = 'unsubscribed',
      unsubscribed_at = pg_catalog.now(),
      confirmation_token_hash = NULL,
        confirmation_expires_at = NULL
      WHERE id = p_subscription_id
    AND status IN ('active', 'pending');

  RETURN FOUND;
END;
$$;

REVOKE ALL ON FUNCTION public.solicitar_suscripcion_notificaciones(text, text, boolean, text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.confirmar_suscripcion_notificaciones(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.cancelar_suscripcion_notificaciones(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.solicitar_suscripcion_notificaciones(text, text, boolean, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.confirmar_suscripcion_notificaciones(text) TO service_role;
GRANT EXECUTE ON FUNCTION public.cancelar_suscripcion_notificaciones(bigint) TO service_role;
